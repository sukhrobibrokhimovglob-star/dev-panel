package io.github.devpanel.support;

import java.util.List;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;

/**
 * Creates the panel's tables when they do not exist. Plain {@code CREATE ... IF NOT EXISTS}
 * instead of a Liquibase/Flyway changelog, so the panel never touches the application's own
 * migration history and works whichever tool (or none) the application uses.
 */
public class DevPanelSchema {

  private static final Logger log = LoggerFactory.getLogger(DevPanelSchema.class);

  private static final List<String> STATEMENTS = List.of(
      """
      CREATE TABLE IF NOT EXISTS devpanel_account (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username VARCHAR(64) NOT NULL UNIQUE,
        password_hash VARCHAR(100) NOT NULL,
        role VARCHAR(20) NOT NULL,
        access VARCHAR(20) NOT NULL,
        enabled BOOLEAN NOT NULL,
        must_change_password BOOLEAN NOT NULL,
        created_at TIMESTAMP NOT NULL,
        created_by VARCHAR(64),
        totp_secret VARCHAR(64),
        totp_enabled BOOLEAN DEFAULT FALSE NOT NULL,
        totp_last_step BIGINT DEFAULT 0 NOT NULL
      )""",
      // Tables created by 0.1.0 builds, before two-factor login existed
      "ALTER TABLE devpanel_account ADD COLUMN IF NOT EXISTS totp_secret VARCHAR(64)",
      "ALTER TABLE devpanel_account ADD COLUMN IF NOT EXISTS"
          + " totp_enabled BOOLEAN DEFAULT FALSE NOT NULL",
      "ALTER TABLE devpanel_account ADD COLUMN IF NOT EXISTS"
          + " totp_last_step BIGINT DEFAULT 0 NOT NULL",
      """
      CREATE TABLE IF NOT EXISTS devpanel_session (
        token_hash VARCHAR(64) PRIMARY KEY,
        account_id BIGINT NOT NULL,
        stage VARCHAR(20) NOT NULL,
        created_at TIMESTAMP NOT NULL,
        last_seen_at TIMESTAMP NOT NULL
      )""",
      "CREATE INDEX IF NOT EXISTS devpanel_session_account ON devpanel_session (account_id)",
      // 0.2.0: where a login came from, and when/where 2FA was set up
      "ALTER TABLE devpanel_session ADD COLUMN IF NOT EXISTS client_ip VARCHAR(64)",
      "ALTER TABLE devpanel_session ADD COLUMN IF NOT EXISTS user_agent VARCHAR(300)",
      "ALTER TABLE devpanel_account ADD COLUMN IF NOT EXISTS totp_enabled_at TIMESTAMP",
      "ALTER TABLE devpanel_account ADD COLUMN IF NOT EXISTS totp_enabled_ip VARCHAR(64)",
      """
      CREATE TABLE IF NOT EXISTS devpanel_exception (
        fingerprint VARCHAR(64) PRIMARY KEY,
        type VARCHAR(255) NOT NULL,
        location VARCHAR(500),
        message VARCHAR(1000),
        sample VARCHAR(8000),
        first_seen TIMESTAMP NOT NULL,
        last_seen TIMESTAMP NOT NULL,
        total BIGINT NOT NULL,
        last_trace_id VARCHAR(64)
      )""",
      """
      CREATE TABLE IF NOT EXISTS devpanel_endpoint_hour (
        hour_start TIMESTAMP NOT NULL,
        endpoint VARCHAR(300) NOT NULL,
        instance VARCHAR(100) NOT NULL,
        calls BIGINT NOT NULL,
        server_errors BIGINT NOT NULL,
        client_errors BIGINT NOT NULL,
        avg_ms BIGINT NOT NULL,
        p95_ms BIGINT NOT NULL,
        max_ms BIGINT NOT NULL,
        sql_per_call DOUBLE PRECISION NOT NULL,
        PRIMARY KEY (hour_start, endpoint, instance)
      )""",
      """
      CREATE TABLE IF NOT EXISTS devpanel_deploy (
        started_at TIMESTAMP NOT NULL,
        host VARCHAR(100),
        version VARCHAR(100),
        git_commit VARCHAR(100)
      )""",
      """
      CREATE TABLE IF NOT EXISTS devpanel_request_audit (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        trace_id VARCHAR(64),
        http_method VARCHAR(10),
        path VARCHAR(255),
        status_code INT NOT NULL,
        duration_ms BIGINT NOT NULL,
        client_ip VARCHAR(45),
        occurred_at TIMESTAMP NOT NULL
      )""",
      "CREATE INDEX IF NOT EXISTS devpanel_request_audit_occurred_at"
          + " ON devpanel_request_audit (occurred_at)",
      "CREATE INDEX IF NOT EXISTS devpanel_request_audit_trace_id"
          + " ON devpanel_request_audit (trace_id)");

  /** PostgreSQL only; elsewhere the check in the account service is the only guard. */
  private static final String ONE_SUPER_ADMIN =
      "CREATE UNIQUE INDEX IF NOT EXISTS devpanel_account_one_super_admin"
          + " ON devpanel_account (role) WHERE role = 'SUPER_ADMIN'";

  private final JdbcTemplate jdbcTemplate;

  public DevPanelSchema(JdbcTemplate jdbcTemplate) {
    this.jdbcTemplate = jdbcTemplate;
  }

  public void create() {
    for (String statement : STATEMENTS) {
      try {
        jdbcTemplate.execute(statement);
      } catch (DataAccessException e) {
        // Two instances starting together can race on IF NOT EXISTS; the loser fails harmlessly.
        log.debug("Dev panel schema statement failed, assuming it already exists: {}",
            e.getMessage());
      }
    }
    try {
      jdbcTemplate.execute(ONE_SUPER_ADMIN);
    } catch (DataAccessException e) {
      log.debug("Partial unique index not supported here: {}", e.getMessage());
    }
  }
}
